const (
	fixtureService = "shifts_connections"
	// Reserved fixture-form IDs that cannot name a real connection, instance or
	// connector, so the write probes below can never change tenant state.
	probeID        = "00000000-0000-4000-8000-000000000001"
	probeConnector = "00000000-0000-4000-8000-000000000003"
	// PowerShell returns the 403 body as this generated model instead of an error.
	powerShellErrorModel = "ErrorResponseAutoGenerated2"
)

// forbidden reports the observed app-only outcome: HTTP 403 with code Forbidden.
func forbidden(response *resty.Response, err error) bool {
	return response != nil && response.StatusCode() == 403 && errors.Is(err, auth.ErrForbidden) && labkit.IsHTTP(err, 403)
}

type shiftsObservation struct {
	Success     bool   `json:"success"`
	Connectors  string `json:"connectors"`
	Connections string `json:"connections"`
	Instances   string `json:"instances"`
}

func powerShellShifts(t *testing.T, ctx context.Context) shiftsObservation {
	t.Helper()
	command := labkit.OracleCommand(ctx, "read-shifts-connections.ps1")
	command.WaitDelay = time.Second
	command.Env = []string{}
	for _, key := range []string{"PATH", "HOME", "TMPDIR", "TMP", "TEMP", "LANG", "DOTNET_ROOT", "SystemRoot", "WINDIR", "PSModuleAnalysisCachePath"} {
		if value, ok := os.LookupEnv(key); ok {
			command.Env = append(command.Env, key+"="+value)
		}
	}
	for _, key := range []string{"MSTEAMS_LAB_IDENTITY_FILE", "MSTEAMS_LAB_MODULE_PATH", "MSTEAMS_LAB_AUTH_METHOD"} {
		command.Env = append(command.Env, key+"="+os.Getenv(key))
	}
	command.Env = append(command.Env, "MSTEAMS_LAB_READ_ONLY=1", "MSTEAMS_LAB_POWERSHELL_ORACLE=1")
	var output labkit.OracleBuffer
	defer func() { clear(output.Data) }()
	command.Stdout, command.Stderr = &output, io.Discard
	if command.Run() != nil || output.Exceeded {
		t.Fatal("pinned PowerShell shifts read failed; no output retained")
	}
	var observed shiftsObservation
	decoder := json.NewDecoder(bytes.NewReader(output.Data))
	decoder.DisallowUnknownFields()
	if decoder.Decode(&observed) != nil || !observed.Success {
		t.Fatal("pinned PowerShell shifts projection unavailable")
	}
	return observed
}

// TestAccShiftsConnectionsAuthorizationDenied reads connectors, connections
// and instances. The Shifts connector service denies app-only Teams
// Administrator credentials, so each read must be a typed HTTP 403.
func TestAccShiftsConnectionsAuthorizationDenied(t *testing.T) {
	cfg := labkit.ReadOnlyEnabled(t)
	sdk, _, _ := labkit.SDKClient(t)
	service := sdk.TeamsAdminAPI.ShiftsConnections
	ctx, cancel := context.WithTimeout(t.Context(), cfg.Timeout)
	defer cancel()

	connectors, response, err := service.ListConnectors(ctx)
	labkit.LogAccessResponse(t, response, err)
	if connectors != nil || !forbidden(response, err) {
		t.Fatal("expected shifts connector authorization denial changed; successful reads need separate qualification")
	}
	labkit.WriteResponseFixture(t, fixtureService, "list_connectors", response, nil)
	if values, response, err := service.ListConnections(ctx); values != nil || !forbidden(response, err) {
		t.Fatal("expected shifts connection authorization denial changed")
	}
	if values, response, err := service.ListInstances(ctx); values != nil || !forbidden(response, err) {
		t.Fatal("expected shifts instance authorization denial changed")
	}
	if value, response, err := service.GetConnectionByID(ctx, probeID); value != nil || !forbidden(response, err) {
		t.Fatal("expected shifts connection read denial changed")
	}
	if value, response, err := service.GetInstanceByID(ctx, probeID); value != nil || !forbidden(response, err) {
		t.Fatal("expected shifts instance read denial changed")
	}
	t.Log("shifts connector read denial: passed")

	if labkit.OracleEnabled(t) {
		observed := powerShellShifts(t, ctx)
		if observed.Connectors != powerShellErrorModel || observed.Connections != powerShellErrorModel || observed.Instances != powerShellErrorModel {
			t.Fatal("PowerShell and Go shifts access outcomes differ")
		}
		t.Log("PowerShell 8.1.0 / Go shifts access parity: passed")
	}
}

// TestAccShiftsConnectionsRejectedWrites sends every write to reserved IDs or
// with an example.invalid WFM URL. The service denies them before validation,
// so no connection or instance is created, changed or removed.
func TestAccShiftsConnectionsRejectedWrites(t *testing.T) {
	cfg := labkit.ReadOnlyEnabled(t)
	sdk, _, _ := labkit.SDKClient(t)
	service := sdk.TeamsAdminAPI.ShiftsConnections
	ctx, cancel := context.WithTimeout(t.Context(), cfg.Timeout)
	defer cancel()
	name, state, etag := "msteams-sdk-probe", "Inactive", "probe-etag"
	settings := sc.Settings{"apiUrl": "https://example.invalid"}

	_, response, err := service.CreateConnection(ctx, sc.CreateConnectionRequest{Name: name, ConnectorID: probeConnector, State: state, ConnectorSpecificSettings: settings})
	if !forbidden(response, err) {
		t.Fatal("connection create denial changed")
	}
	labkit.WriteResponseFixture(t, fixtureService, "create_connection", response, nil)
	update := sc.ConnectionUpdate{IfMatch: &etag, Name: &name}
	if _, response, err = service.ReplaceConnectionByID(ctx, probeID, update); !forbidden(response, err) {
		t.Fatal("connection replace denial changed")
	}
	if _, response, err = service.UpdateConnectionByID(ctx, probeID, update); !forbidden(response, err) {
		t.Fatal("connection update denial changed")
	}
	if response, err = service.DeleteConnectionByID(ctx, probeID); !forbidden(response, err) {
		t.Fatal("connection delete denial changed")
	}
	if response, err = service.Validate(ctx, sc.ValidateRequest{Name: name, ConnectorID: probeConnector, ConnectorSpecificSettings: settings}); !forbidden(response, err) {
		t.Fatal("connection validation denial changed")
	}
	t.Log("shifts connection write denial: passed")

	id := probeID
	instance := sc.InstanceRequest{ConnectionID: &id, Name: &name, State: &state}
	if _, response, err = service.CreateInstance(ctx, instance); !forbidden(response, err) {
		t.Fatal("instance create denial changed")
	}
	if _, response, err = service.ReplaceInstanceByID(ctx, probeID, sc.InstanceUpdate{IfMatch: etag, InstanceRequest: instance}); !forbidden(response, err) {
		t.Fatal("instance replace denial changed")
	}
	if _, response, err = service.UpdateInstanceByID(ctx, probeID, sc.InstanceUpdate{IfMatch: etag, InstanceRequest: sc.InstanceRequest{Name: &name}}); !forbidden(response, err) {
		t.Fatal("instance update denial changed")
	}
	if response, err = service.DeleteInstanceByID(ctx, probeID); !forbidden(response, err) {
		t.Fatal("instance delete denial changed")
	}
	t.Log("shifts instance write denial: passed")
}
